//! 命令文法：把一条命令行变成 [`Command`]。
//!
//! 这里是内核里唯一的解析器。它只做文法分析，不做权限判定、不接触文件系统、不执行任何
//! 东西——那些都在执行器里，且必须在解析结果之上进行，否则"执行前预检"就无法成立。
//!
//! 版本一只支持单命令：参数、`>` `>>` `<` 重定向、单个 heredoc。管道、命令替换、
//! 反引号、逻辑连接、通配符、后台执行一律拒绝，理由是它们会让写入目标集合在执行前
//! 不可知（管道则让"一条命令"不再对应一次工具调用）。

mod ast;
mod error;

pub use ast::{Command, HereDoc, Redirect, RedirectKind};
pub use error::ParseError;
